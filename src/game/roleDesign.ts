//
// 审美原则（建模层必须遵守）：
//   1. 对称与留白 —— 中轴对称为骨，但必留透空与负形（体侧、足下、袖口、棂格、轮辐、
//      层与层之间都要透气），忌把剪影填满成实心团块。
//   2. 曲线优于直棱 —— 躯干、衣纹、飘带、飞檐、枝干、船体一律用 S 形 / 缓弧 / 举折，
//      忌等粗圆柱、方盒、平板；转角圆润，顿挫有致。
//   3. 朱青金为主 —— 朱砂、石青、石绿、赤金为骨架色，按约 6:3:1 分配，金只用于
//      冠、带、背光边、袖缘、勾线等点睛处，忌通体金。
//   4. 低饱和矿物色 —— 取石青、石绿、赭石、黛蓝、月白、缟素等矿物 / 植物色，
//      明度沉稳；忌高饱和荧光色、忌塑料反光、忌霓虹式自发光铺满。
//   5. 国漫 / 工笔重彩的线条感 —— 每个部件都要一道清晰的「勾线」：领缘、袖口、
//      叶缘、口沿、瓦垄边、旗缘用异色窄边条勾勒；纹样浅浮雕或细线，不做满身碎花。
//
// 纪律：纯 TS 数据模块，无 DOM、无 three、无第三方库、无任何 import；designFor 纯确定性，
//       禁止 Math.random / Date.now，同一输入必返回逐字段相同的对象；不修改任何现有文件。
// ============================================================================

export type DesignDomain =
  | 'deity' | 'dragon' | 'beast' | 'bird' | 'humanoid'
  | 'spirit' | 'plant' | 'building' | 'item' | 'vehicle';

