// ---------------------------------------------------------------------------
// 确定性工具：整数 hash（FNV-1a）与数组旋转。禁止 Math.random / Date.now。
// ---------------------------------------------------------------------------
function hashStr(s: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h = Math.imul(h ^ s.charCodeAt(i), 0x01000193);
  }
  return h >>> 0;
}

function rotate<T>(arr: T[], by: number): T[] {
  const n = arr.length;
  if (n === 0) return [];
  const k = ((by % n) + n) % n;
  return arr.slice(k).concat(arr.slice(0, k));
}

// 按 domain 取基准形象，再按名号 hash 稳定地从 references / motifs / palette / ornaments
// 中「选」出主项并旋转次序，把主纹样、首选参考、主色、主佩饰写进 notes 后缀做微调。
// 纯函数、不改动 ROLE_DESIGNS 原对象、无随机、无时间；同一 (domain, name) 输入必返回
// 逐字段完全相同的结果。name 缺省时以 domain 自身为键，行为同样确定。
export function designFor(domain: DesignDomain, name?: string): RoleDesign {
  const base = ROLE_DESIGNS[domain];
  const key = name && name.length > 0 ? name : domain;
  const h = hashStr(key) >>> 0;

  const motifs = rotate(base.motifs, h);
  const references = rotate(base.references, h >>> 3);
  const palette = rotate(base.palette, h >>> 7);
  const ornaments = rotate(base.ornaments, h >>> 11);

  const primaryMotif = motifs[0] ?? '';
  const primaryRef = references[0] ?? '';
  const mainHex = (palette[0] ?? 0).toString(16).padStart(6, '0').toUpperCase();
  const primaryOrnament = ornaments[0] ?? '';
  const suffix = `（按名号「${key}」择：主纹样「${primaryMotif}」，首选参考「${primaryRef}」，主色 #${mainHex}，主佩饰「${primaryOrnament}」）`;

  return {
    domain: base.domain,
    title: base.title,
    silhouette: base.silhouette,
    headwear: base.headwear.slice(),
    garment: base.garment.slice(),
    ornaments,
    props: base.props.slice(),
    palette,
    references,
    motifs,
    notes: base.notes + suffix,
  };
}
