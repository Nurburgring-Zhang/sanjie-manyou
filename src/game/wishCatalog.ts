const NAME_SET = new Set<string>();

/** 全量目录（构建即去重；顺序稳定，id 单调递增） */
export const WISH_CATALOG: CatalogEntry[] = (() => {
  const out: CatalogEntry[] = [];
  let n = 0;
  for (const g of GROUPS) {
    for (const name of g.names) {
      if (!name || NAME_SET.has(name)) continue;
      NAME_SET.add(name);
      n += 1;
      out.push({
        id: 'w' + String(n).padStart(3, '0'),
        name,
        category: g.category,
        source: g.source,
        archetype: g.archetype,
        traits: [...g.traits],
        colors: [...g.colors],
        scale: g.scale,
        rarity: g.rarity,
        lore: `${name}·${g.desc}（出典：${g.source}）`,
      });
    }
  }
  return out;
})();

const BY_ID = new Map<string, CatalogEntry>(WISH_CATALOG.map((e) => [e.id, e]));

export function getById(id: string): CatalogEntry | undefined {
  return BY_ID.get(id);
}

/** 目录检索：名称/分类/出典/特质/描述包含即命中；精确名 > 前缀 > 其它 */
export function searchCatalog(q: string): CatalogEntry[] {
  const s = (q ?? '').trim();
  if (!s) return WISH_CATALOG.slice();
  const hits = WISH_CATALOG.filter((e) =>
    e.name.includes(s) || e.category.includes(s) || e.source.includes(s) ||
    e.traits.some((t) => t.includes(s)) || e.lore.includes(s));
  const rank = (e: CatalogEntry): number =>
    e.name === s ? 0 : e.name.startsWith(s) ? 1 : e.name.includes(s) ? 2 : 3;
  return hits.sort((a, b) => rank(a) - rank(b) || a.name.length - b.name.length);
}

/** 在自由文本里找「最长的、被包含的真实名号」——L1 复用预设的唯一入口 */
export function matchCatalog(text: string): CatalogEntry | null {
  let best: CatalogEntry | null = null;
  for (const e of WISH_CATALOG) {
    if (text.includes(e.name) && (!best || e.name.length > best.name.length)) best = e;
  }
  return best;
}

