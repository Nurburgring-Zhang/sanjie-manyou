// 八类愿景 · 权威语义分类（只匹配「愿望名词本身」，绝不读预设条目的通用描述文字）
// ----------------------------------------------------------------------------
// 背景：旧版 classify() 把设计文档里的通用描述（SURFACE「灵纹」/ MOTIFS「莲纹·缠枝纹」）
// 一并喂进关键词扫描，导致「山/皇宫/猫/汽车」被误判成 spirit / plant 通用原型。
// 这里把「名词 → 语义类 → 原型/复数/形状标签」收敛为唯一权威入口，wishAgent /
// assetPipeline / wishPanel / wishForge 全部复用它，保证同一愿望全链结论一致。
// 纯正则 + 整数常量，无 Math.random / 无共享 RNG / 无网络 / 无 DOM。
// ============================================================================

/** 语义形状标签：forge 据此调用专用建模函数（WishSpec.shape），archetype 仍为旧 10 类兼容值 */
export type WishShape =
  | 'cat' | 'palace' | 'mountain' | 'army' | 'battalion'
  | 'car' | 'spaceship' | 'alien';

export interface WishClass {
  shape: WishShape;
  /** 规范化中文名：写进 spec.name / 资料卡 / 提示文案，不再用被量词污染的 cleanName */
  name: string;
  /** 兼容旧 10 类 archetype，供未带 shape 的旧链路 / 装饰层 / tick 使用 */
  archetype: Archetype;
  /** 确定性实体数量：军队/天兵天将 >1；不消耗共享 RNG（固定常量） */
  count: number;
}

interface WishRule { re: RegExp; c: WishClass }

/** 顺序：更具体的多字词在前、单字「山」兜底放最后，避免通用描述文字误命中 */
const WISH_RULES: WishRule[] = [
  { re: /天兵天将|天兵|天将|神兵|天军/,
    c: { shape: 'battalion', name: '天兵天将', archetype: 'humanoid', count: 36 } },
  { re: /军队|大军|军团|部队|兵马|士兵|军阵|禁军/,
    c: { shape: 'army', name: '军队', archetype: 'humanoid', count: 24 } },
  { re: /皇宫|宫殿|宫城|故宫|宫阙|palace/i,
    c: { shape: 'palace', name: '皇宫', archetype: 'building', count: 1 } },
  { re: /猫|猫咪|小猫|狸猫|cat/i,
    c: { shape: 'cat', name: '猫', archetype: 'beast', count: 1 } },
  { re: /特斯拉|汽车|轿车|电动车|tesla|sedan|\bcar\b/i,
    c: { shape: 'car', name: '特斯拉汽车', archetype: 'vehicle', count: 1 } },
  { re: /宇宙飞船|太空船|飞船|星舰|飞碟|spaceship|\bufo\b/i,
    c: { shape: 'spaceship', name: '宇宙飞船', archetype: 'vehicle', count: 1 } },
  { re: /外星人|外星生物|异形|alien|\bet\b/i,
    c: { shape: 'alien', name: '外星人', archetype: 'humanoid', count: 1 } },
  { re: /山峰|高山|大山|山体|一座山|山脉|mountain|山/i,
    c: { shape: 'mountain', name: '山', archetype: 'building', count: 1 } },
];

/** 权威分类：命中返回语义类（含 shape/count），未命中返回 null（交回旧预设/L2 链路） */
export function classifyWish(text: string): WishClass | null {
  const t = String(text ?? '');
  for (const r of WISH_RULES) if (r.re.test(t)) return { ...r.c };
  return null;
}

